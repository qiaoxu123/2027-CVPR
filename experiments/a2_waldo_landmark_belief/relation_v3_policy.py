"""Frozen original A0/controller with the opt-in, public-only V3 branch."""
import json,time
from pathlib import Path
import torch
from .paths import ROOT,A0_SHA,sha
from .collected_snapshot import BASE
from .policy import A2Policy,updated_field
from .relation_v3_model import RelationV3Network
from .relation_v3_runtime import public_network_inputs,runtime_forward


from .relation_v3_provenance import checked_state,validate_gate


class RelationV3Policy(A2Policy):
    def __init__(self,directory,checkpoint,calibration=None,*,control='real',functional_only=False):
        state=checked_state(checkpoint,functional_only=functional_only)
        parameters=dict(enabled=False,minimum_gain=1.,maximum_harm=0.,temperature=1.)
        if calibration:
            parameters=json.loads(Path(calibration).read_text())
            if parameters['checkpoint_sha256']!=sha(checkpoint):raise ValueError('V3 gate/checkpoint mismatch')
            if functional_only:
                if parameters.get('scope')!='TRAIN_functional_only' or parameters.get('gate_final') is not False:
                    raise ValueError('Functional override must be explicitly TRAIN-only and nonfinal')
            else:validate_gate(parameters,state)
        self.functional_episodes=None
        if functional_only:
            preflight=BASE/'revision_v3/preflight';signature=json.loads((preflight/'signature.json').read_text())
            public_path=preflight/'public_episodes.json'
            if (signature['initial_checkpoint_sha256']!=sha(checkpoint) or signature['code_sha256']!=state['code_sha256']
                or signature['roles_sha256']!=state['roles_sha256'] or signature['public_episodes_sha256']!=sha(public_path)):
                raise ValueError('Pinned functional TRAIN episode list required')
            self.functional_episodes=json.loads(public_path.read_text())
            if len(self.functional_episodes)!=32:raise ValueError('All32 functional TRAIN episodes required')
        super().__init__(directory,collect=True,control=control)
        self.branch=RelationV3Network(**state['model_config']).to(self.device).eval().requires_grad_(False)
        self.branch.load_state_dict(state['model'],strict=True)
        self.v3_parameters=parameters

    def set_episode(self,episode,transform,catalog):
        # Functional-only state must not be attached to arbitrary benchmark
        # episodes. Bind exact TRAIN map/instruction/start rather than rely on
        # a caller-supplied split label. The list is generated by preflight.
        if getattr(self,'functional_episodes',None) is not None:
            import numpy as np
            matched=any(e['map_name']==episode.map_name and e['instruction']==episode.instruction
                        and np.array_equal(np.asarray(e['start_pose']),np.asarray(episode.start_pose)) for e in self.functional_episodes)
            if not matched:raise ValueError('Functional policy is limited to predeclared TRAIN episodes')
        super().set_episode(episode,transform,catalog)

    def _refine(self,module,args,out):
        self.original_field=out.belief;self.corrected_field=out.belief;start=time.perf_counter()
        self.pack,self.meta=self.perception.extract(self,self.current_state,out.belief)
        network=public_network_inputs(self.pack,self.meta)
        if self.control=='no_text':
            network=dict(network,instruction_tokens=torch.zeros_like(network['instruction_tokens']),
                         landmark_name_tokens=torch.zeros_like(network['landmark_name_tokens']))
        parameters=self.v3_parameters if self.control!='zero' else dict(self.v3_parameters,enabled=False)
        with torch.autocast('cuda',enabled=False):
            self.branch_output=self.branch(**{k:v[None] for k,v in network.items()},control=self.control)
            mixed,info,self.risk_output=runtime_forward(self.pack['spatial'],self.branch_output,self.branch,parameters)
        out.belief=updated_field(out.belief,self.inputs['grid_xy'],mixed);self.corrected_field=out.belief
        self.local_diagnostics=dict(a2_updated=info['updated'],a2_fallback=info['gate']==0.,a2_alpha=info['gate'],
            a2_gain_score=info['gain_score'],a2_harm_score=info['harm_score'],a2_candidates=len(self.meta['candidates']),
            a2_valid_references=self.meta['valid_references'],a2_detection_error=self.meta['detector_error'],a2_seconds=time.perf_counter()-start)
        return out
